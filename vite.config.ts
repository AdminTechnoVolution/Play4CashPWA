import { defineConfig, loadEnv } from 'vite';
import react from '@vitejs/plugin-react';
import { VitePWA } from 'vite-plugin-pwa';
import { execSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

function readPackageVersion(): string {
  try {
    const pkg = JSON.parse(readFileSync(resolve(__dirname, 'package.json'), 'utf8')) as { version?: string };
    return pkg.version || '0.0.0';
  } catch {
    return '0.0.0';
  }
}

function readGitShortSha(): string {
  try {
    return execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] })
      .toString()
      .trim();
  } catch {
    return 'nogit';
  }
}

const APP_VERSION = readPackageVersion();
const APP_GIT_SHA = readGitShortSha();
const APP_FULL_VERSION = `${APP_VERSION}+${APP_GIT_SHA}`;

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '');
  const proxyTarget = env.VITE_DEV_PROXY_TARGET || '';
  const proxyInsecure = env.VITE_DEV_PROXY_INSECURE === 'true';

  // When VITE_DEV_PROXY_TARGET is set, route /api and /socket.io to it so the SPA
  // shares the API's origin in dev. This sidesteps cross-origin SameSite=None cookie
  // pitfalls for the httpOnly refresh token.
  const proxy = proxyTarget
    ? {
        '/api': {
          target: proxyTarget,
          changeOrigin: true,
          secure: !proxyInsecure,
          cookieDomainRewrite: '',
        },
        '/socket.io': {
          target: proxyTarget,
          changeOrigin: true,
          secure: !proxyInsecure,
          ws: true,
        },
      }
    : undefined;

  return {
    define: {
      __APP_VERSION__: JSON.stringify(APP_VERSION),
      __APP_GIT_SHA__: JSON.stringify(APP_GIT_SHA),
      __APP_FULL_VERSION__: JSON.stringify(APP_FULL_VERSION),
      __APP_BUILD_TIME__: JSON.stringify(new Date().toISOString()),
    },
    plugins: [
      react(),
      VitePWA({
        // 'prompt' = SW downloads in background but does NOT auto-activate.
        // The app shows a modal and the user decides when to apply the update.
        registerType: 'prompt',
        devOptions: { enabled: true },
        includeAssets: ['icons/*.png', 'icons/*.svg'],
        manifest: {
          name: 'Play4Cash',
          short_name: 'Play4Cash',
          description: 'Play4Cash — Multiplayer games platform',
          theme_color: '#0a1628',
          background_color: '#0a1628',
          display: 'standalone',
          orientation: 'portrait',
          scope: '/',
          start_url: '/',
          icons: [
            { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
            { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
            { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }
          ]
        },
        workbox: {
          globPatterns: ['**/*.{js,css,html,ico,png,svg,woff2}'],
          // Discard old caches generated by previous SW versions so chunks from outdated
          // builds don't linger and cause ChunkLoadError after a deploy.
          cleanupOutdatedCaches: true,
          // SPA fallback so deep links work offline / cached.
          navigationPreload: true,
          navigateFallback: '/index.html',
          // Don't claim clients on activate — we want the user to opt in via the modal.
          clientsClaim: false,
          skipWaiting: false,
          runtimeCaching: [
            {
              urlPattern: /^https:\/\/p4c-api/,
              handler: 'NetworkFirst',
              options: { cacheName: 'api-cache', expiration: { maxEntries: 50, maxAgeSeconds: 300 } }
            }
          ]
        }
      })
    ],
    server: {
      port: 3000,
      proxy,
    },
    resolve: {
      dedupe: ['react', 'react-dom'],
    },
    optimizeDeps: {
      include: ['socket.io-client', 'react', 'react-dom'],
    }
  };
});
