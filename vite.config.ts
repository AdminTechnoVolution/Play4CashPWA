import { defineConfig, loadEnv, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { VitePWA } from 'vite-plugin-pwa';
import { execSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const CONFIG_DIR = fileURLToPath(new URL('.', import.meta.url));

function readPackageVersion(): string {
  try {
    const pkg = JSON.parse(readFileSync(resolve(CONFIG_DIR, 'package.json'), 'utf8')) as { version?: string };
    return pkg.version || '0.0.0';
  } catch {
    return '0.0.0';
  }
}

function readGitShortSha(): string {
  try {
    return execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] })
      .toString()
      .trim();
  } catch {
    return 'nogit';
  }
}

const APP_VERSION = readPackageVersion();
const APP_GIT_SHA = readGitShortSha();
const APP_FULL_VERSION = `${APP_VERSION}+${APP_GIT_SHA}`;

/** Loads /env-config.js before the app bundle so window.__P4C_ENV__ is ready. */
function injectRuntimeEnvConfig(): Plugin {
  return {
    name: 'inject-runtime-env-config',
    transformIndexHtml: {
      order: 'pre',
      handler() {
        return [
          {
            tag: 'script',
            attrs: { src: '/env-config.js' },
            injectTo: 'head-prepend',
          },
        ];
      },
    },
  };
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '');
  const proxyTarget = env.VITE_DEV_PROXY_TARGET || '';
  const proxyInsecure = env.VITE_DEV_PROXY_INSECURE === 'true';

  // When VITE_DEV_PROXY_TARGET is set, route /api and /socket.io to it so the SPA
  // shares the API's origin in dev. This sidesteps cross-origin SameSite=None cookie
  // pitfalls for the httpOnly refresh token.
  const proxy = proxyTarget
    ? {
        '/api': {
          target: proxyTarget,
          changeOrigin: true,
          secure: !proxyInsecure,
          cookieDomainRewrite: '',
        },
        '/socket.io': {
          target: proxyTarget,
          changeOrigin: true,
          secure: !proxyInsecure,
          ws: true,
        },
      }
    : undefined;

  return {
    define: {
      __APP_VERSION__: JSON.stringify(APP_VERSION),
      __APP_GIT_SHA__: JSON.stringify(APP_GIT_SHA),
      __APP_FULL_VERSION__: JSON.stringify(APP_FULL_VERSION),
      __APP_BUILD_TIME__: JSON.stringify(new Date().toISOString()),
    },
    build: {
      // Main bundle includes Ionic + game modules; warn above ~2.5 MB instead of 500 kB default.
      chunkSizeWarningLimit: 10000,
    },
    plugins: [
      injectRuntimeEnvConfig(),
      react(),
      VitePWA({
        // 'prompt' = SW downloads in background but does NOT auto-activate.
        // The app shows a modal and the user decides when to apply the update.
        registerType: 'prompt',
        devOptions: { enabled: true },
        includeAssets: ['icons/*.png', 'icons/*.svg'],
        manifest: {
          name: 'Play4Cash',
          short_name: 'Play4Cash',
          description: 'Play4Cash — Multiplayer games platform',
          theme_color: '#0a1628',
          background_color: '#0a1628',
          display: 'standalone',
          orientation: 'portrait',
          scope: '/',
          start_url: '/',
          icons: [
            { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
            { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
            { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }
          ]
        },
        workbox: {
          globPatterns: ['**/*.{js,css,html,ico,png,svg,woff2}'],
          globIgnores: ['**/env-config.js'],
          // Default Workbox limit is 10 MiB; main JS bundle can exceed that as games/i18n grow.
          maximumFileSizeToCacheInBytes: 10 * 1024 * 1024,
          // Discard old caches generated by previous SW versions so chunks from outdated
          // builds don't linger and cause ChunkLoadError after a deploy.
          cleanupOutdatedCaches: true,
          // SPA fallback so deep links work offline / cached.
          navigationPreload: true,
          navigateFallback: '/index.html',
          // Claim clients when a worker **activates**. Updates still wait in `waiting` until the user
          // confirms (`skipWaiting: false` + modal); without claim, `controllerchange` may never fire
          // on the open tab and eager reload can race activation (stale chunks until another tap).
          clientsClaim: true,
          skipWaiting: false,
          importScripts: ['sw-push.js'],
          runtimeCaching: [
            {
              urlPattern: /\/env-config\.js$/,
              handler: 'NetworkOnly',
            },
            {
              // Never cache authenticated API traffic. Cookies + auth refresh must always hit network,
              // otherwise a stale cached 401 can mask a valid session.
              urlPattern: /^https:\/\/p4c-api/,
              handler: 'NetworkOnly',
            }
          ]
        }
      })
    ],
    server: {
      port: 3000,
      proxy,
    },
    resolve: {
      dedupe: ['react', 'react-dom'],
    },
    optimizeDeps: {
      include: ['socket.io-client', 'react', 'react-dom'],
    }
  };
});
